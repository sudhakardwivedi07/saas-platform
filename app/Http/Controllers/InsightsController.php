    public function index(Request $request)
    {
        $user      = auth()->user();
        $companyId = $user->company_id;

        // Check QB connection by portfolio companies (admin may have connected on client's behalf)
        $portfolioIds = $user->portfolioCompanies()->pluck('id');
        if ($portfolioIds->isEmpty()) {
            $portfolioIds = collect([$companyId])->filter();
        }
        $this->qbConnection = QuickBooksConnection::withoutGlobalScopes()
            ->whereIn('company_id', $portfolioIds)
            ->where('is_active', true)
            ->first();

        $this->qbConfigured = $this->resolveCredentials($companyId) !== null;

        // Same company list as My Companies / KPI (portfolio)
        $allCompanies = $user->portfolioCompanies();

        $this->companies = $allCompanies;

        $defaultId = (int) ($allCompanies->first()?->id ?: $companyId);
        $selectedCompanyId = (int) $request->get('company_id', $defaultId);
        if (! $allCompanies->contains(fn ($c) => (int) $c->id === $selectedCompanyId)) {
            $selectedCompanyId = $defaultId;
        }
        $this->selectedCompanyId = $selectedCompanyId;
        $this->selectedCompany   = $allCompanies->firstWhere('id', $this->selectedCompanyId);

        // Load reports — include soft-deleted so deleted records show with "Deleted" status.
        // When admin is impersonating, also include reports generated by the admin for this company,
        // since the admin may have connected QB and generated insights on the client's behalf.
        $impersonatingAdminId = $this->resolveImpersonatingAdminId();
        $this->reports = Report::withTrashed()
            ->where(function ($q) use ($user, $selectedCompanyId, $impersonatingAdminId) {
                // Client's own reports for the selected company
                $q->where(function ($inner) use ($user, $selectedCompanyId) {
                    $inner->where('user_id', $user->id)
                        ->where(function ($q2) use ($selectedCompanyId, $user) {
                            $q2->where('company_id', $selectedCompanyId);
                            if ((int) $selectedCompanyId === (int) $user->company_id) {
                                $q2->orWhereNull('company_id');
                            }
                        });
                });
                // Reports generated by the impersonating admin for this company
                if ($impersonatingAdminId) {
                    $q->orWhere(function ($inner) use ($impersonatingAdminId, $selectedCompanyId) {
                        $inner->where('user_id', $impersonatingAdminId)
                            ->where('company_id', $selectedCompanyId);
                    });
                }
            })
            ->orderByDesc('created_at')
            ->get()
            ->groupBy(fn($r) => $r->report_name . '||' . $r->company_id)
            ->map(fn($group) => $group->sortByDesc('version')->first())
            ->values();

        // Monthly usage for limit enforcement (same scope as the reports list above)
        $this->monthlyUsed  = $this->countMonthlyInsights($user->id, (int) $selectedCompanyId, (int) $user->company_id);
        $this->monthlyLimit = $this->resolveMonthlyLimit($companyId);

        // Current plan info for the limit-reached modal
        $company = Company::withoutGlobalScopes()->find($companyId);
        $this->currentPlan = $company?->clientPackage ?? $company?->package;

        return view('insights.index', $this->data);
    }

