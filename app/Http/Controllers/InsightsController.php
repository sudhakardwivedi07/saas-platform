    /**
     * Returns the admin ID when an admin is impersonating a client, whether via
     * session-based impersonation or per-request token-based impersonation (?_imp=TOKEN).
     */
    private function resolveImpersonatingAdminId(): ?int
    {
        // Session-based impersonation (admin opened "View as Client" in same tab)
        if ($id = session('impersonating_client_original_id')) {
            return (int) $id;
        }

        // Token-based impersonation (?_imp=TOKEN — new tab, no session changes)
        $token = request()->query('_imp');
        if ($token) {
            $data = Cache::get('imp_view_' . $token);
            if ($data && isset($data['admin_id'])) {
                return (int) $data['admin_id'];
            }
        }

        return null;
    }

    private function resolveMonthlyLimit(int $companyId): ?int
    {
        $company = Company::withoutGlobalScopes()->find($companyId);
        if (!$company) return null;

        $plan = $company->clientPackage ?? $company->package;
        if (!$plan) return null;

        $limit = $plan->insights_per_month ?? $plan->max_insights_per_month ?? null;
        return $limit ? (int) $limit : null;
    }

